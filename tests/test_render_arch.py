class ValidateCase(unittest.TestCase):
    """Runs `render_arch.py validate` on a model built from the fixture."""

    def validate(self, model):
        tmp = temp_dir(self)
        root = fixture_root(tmp, model)
        return run_py(["validate", "--model", write_model(tmp, model),
                       "--root", root])

    def assertRejected(self, model, *needles):
        r = self.validate(model)
        self.assertEqual(r.returncode, 1, f"expected rejection\n{r.stderr}")
        for needle in needles:
            self.assertIn(needle, r.stderr)
        return r

    def assertAccepted(self, model):
        r = self.validate(model)
        self.assertEqual(r.returncode, 0, r.stderr)
        return r


class Fixtures(unittest.TestCase):
    """Guards the helpers the rest of this module builds on."""

    def test_model_fixture_has_required_top_level_keys(self):
        model = model_fixture()
        self.assertEqual(
            sorted(model), ["components", "flows", "interactions", "title"]
        )

    def test_model_fixture_is_json_serialisable(self):
        json.dumps(model_fixture())

    def test_model_fixture_declares_one_main_flow(self):
        flows = model_fixture()["flows"]
        self.assertEqual([f["id"] for f in flows if f["kind"] == "main"], ["main"])

    def test_model_fixture_interactions_reference_declared_components(self):
        model = model_fixture()
        ids = {c["id"] for c in model["components"]}
        for inter in model["interactions"]:
            self.assertIn(inter["from"], ids)
            self.assertIn(inter["to"], ids)

    def test_model_fixture_declares_an_actor_without_a_path(self):
        actors = [c for c in model_fixture()["components"] if c["layer"] == "actor"]
        self.assertTrue(actors)
        self.assertIsNone(actors[0]["path"])

    def test_overrides_replace_top_level_keys(self):
        self.assertEqual(model_fixture(title="other")["title"], "other")

    def test_fixture_root_creates_a_file_for_every_non_null_path(self):
        model = model_fixture()
        root = fixture_root(temp_dir(self), model)
        paths = [c["path"] for c in model["components"] if c["path"]]
        self.assertTrue(paths, "fixture must declare at least one real path")
        for path in paths:
            self.assertTrue((root / path).exists(), path)

    def test_fixture_root_creates_nothing_for_a_null_path(self):
        model = model_fixture()
        root = fixture_root(temp_dir(self), model)
        created = sorted(p.relative_to(root).as_posix()
                         for p in root.rglob("*") if p.is_file())
        expected = sorted(c["path"] for c in model["components"] if c["path"])
        self.assertEqual(created, expected)


