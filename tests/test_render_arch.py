class PumlCase(unittest.TestCase):
    """Renders a model to .puml and returns the text."""

    def render(self, model, extra=(), expect=0):
        tmp = temp_dir(self)
        root = fixture_root(tmp, model)
        out = tmp / "architecture.puml"
        r = run_py(["puml", "--model", write_model(tmp, model),
                    "--out", out, "--root", root, *extra])
        self.assertEqual(r.returncode, expect, r.stderr or r.stdout)
        if expect == 0:
            return out.read_text()
        return r.stderr


class PumlDeterminism(PumlCase):

    def test_determinism_survives_reordered_model_entries(self):
        model = rich_model()
        shuffled = {
            "title": model["title"],
            "components": list(reversed(model["components"])),
            "flows": list(reversed(model["flows"])),
            "interactions": list(reversed(model["interactions"])),
        }
        self.assertNotEqual(model["components"], shuffled["components"])
        self.assertEqual(self.render(model), self.render(shuffled))

    def test_determinism_orders_participants_by_layer_then_id(self):
        text = self.render(rich_model())
        order = re.findall(r"^(?:participant|actor) .* as (\w+)$", text,
                           re.MULTILINE)
        # actor, api, service, data -> LAYERS order; alphabetical inside.
        self.assertEqual(order, ["Developer", "Api", "Worker", "Store"])

    def test_determinism_orders_boxes_by_the_layer_vocabulary(self):
        text = self.render(rich_model())
        self.assertEqual(
            re.findall(r"^' layer:(\w+)$", text, re.MULTILINE),
            ["actor", "api", "service", "data"],
        )

    def test_determinism_puts_main_flow_before_independent_groups(self):
        text = self.render(rich_model())
        first_message = text.index("uruchamia discover")
        self.assertLess(first_message, text.index("group "))

    def test_determinism_orders_independent_flows_alphabetically_by_id(self):
        text = self.render(rich_model())
        self.assertEqual(
            re.findall(r"^' flow:([\w-]+)$", text, re.MULTILINE),
            ["cron", "prepush"],
        )

    def test_determinism_orders_messages_by_seq(self):
        text = self.render(rich_model())
        self.assertEqual(
            re.findall(r"^\w+ -> \w+ : (\w+) ", text, re.MULTILINE)[:3],
            ["uruchamia", "zleca", "zapisuje"],
        )

    def test_determinism_breaks_seq_ties_without_reading_file_order(self):
        model = rich_model()
        for inter in model["interactions"]:
            inter["seq"] = 10
        shuffled = dict(model,
                        interactions=list(reversed(model["interactions"])))
        self.assertEqual(self.render(model), self.render(shuffled))


class PumlClock(PumlCase):
    """The diagram must not carry any value that varies with time.

    Deliberately not a grep for a year digit or the word 'date': that
    would reject a legitimate op named 'update' or a DateService
    component. These assert the exact time-varying values that the
    Markdown document injects, and that the diagram must not.
    """

    def test_clock_omits_todays_date_in_every_common_format(self):
        text = self.render(rich_model())
        today = datetime.date.today()
        for fmt in ("%Y-%m-%d", "%d.%m.%Y", "%d/%m/%Y", "%Y%m%d"):
            self.assertNotIn(today.strftime(fmt), text)

    def test_clock_omits_the_current_year(self):
        # Safe to assert for the fixture: no label, verb or op contains it.
        text = self.render(rich_model())
        self.assertNotIn(str(datetime.date.today().year), text)

    def test_clock_omits_the_head_commit_sha(self):
        sha = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, check=True,
        ).stdout.strip()
        self.assertNotIn(sha, self.render(rich_model()))

    def test_clock_two_renders_in_sequence_are_identical(self):
        model = rich_model()
        self.assertEqual(self.render(model), self.render(model))


class PumlStructure(PumlCase):

    def test_puml_structure_wraps_each_participant_in_its_layer_box(self):
        text = self.render(rich_model())
        blocks = re.findall(
            r"^box \"([^\"\n]+)\"\n' layer:(\w+)\n(.*?)\n^end box$",
            text, re.MULTILINE | re.DOTALL)
        self.assertEqual(len(blocks), 4)
        for label, layer, body in blocks:
            self.assertTrue(body.strip(), f"{layer} box is empty")
            for line in body.strip().splitlines():
                self.assertRegex(line, r"^(participant|actor) ")

    def test_puml_structure_anchors_every_layer_box(self):
        text = self.render(rich_model())
        self.assertEqual(text.count("box \""), text.count("' layer:"))

    def test_puml_structure_anchors_every_group(self):
        text = self.render(rich_model())
        self.assertEqual(
            len(re.findall(r"^group ", text, re.MULTILINE)),
            len(re.findall(r"^' flow:", text, re.MULTILINE)),
        )

    def test_puml_structure_does_not_group_the_main_flow(self):
        text = self.render(rich_model())
        self.assertNotIn("' flow:main", text)
        self.assertNotIn("group Instalacja", text)

    def test_puml_structure_labels_every_arrow_with_verb_and_op(self):
        text = self.render(rich_model())
        arrows = re.findall(r"^\w+ -> \w+ : (.+)$", text, re.MULTILINE)
        self.assertEqual(len(arrows), 5)
        for label in arrows:
            self.assertEqual(len(label.split(" ", 1)), 2, label)

    def test_puml_structure_opens_and_closes_the_diagram(self):
        text = self.render(rich_model())
        self.assertTrue(text.startswith("@startuml\n"))
        self.assertTrue(text.endswith("@enduml\n"))

    def test_puml_structure_carries_the_title(self):
        self.assertIn("title rich", self.render(rich_model()))


